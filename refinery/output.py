def _t(ev: Evidence) -> dict:
    return TEXT[ev.lang]


def labels(ev: Evidence) -> dict:
    t = _t(ev)
    return {"up": ev.trend_labels.get("up", t["up"]), "down": ev.trend_labels.get("down", t["down"])}


def metric_label(ev: Evidence, mid: str) -> str:
    m = ev.metrics[mid]
    return f"{m['label']} ({m['unit']})" if m.get("unit") else m["label"]


def sort_label(ev: Evidence, by: str) -> str:
    return _t(ev)["score"] if by == "score" else ev.metrics[by]["label"]


def columns(ev: Evidence, by: str) -> dict[str, str]:
    """列名 → 说明。CSV 的列说明文件和网页里的折叠说明都用它。"""
    t, lb = _t(ev), labels(ev)
    cols = {
        t["rank"]: t["help_rank"].format(sort=sort_label(ev, by)),
        t["name"]: t["help_name"],
        t["subtitle"]: t["help_subtitle"],
        t["tags"]: t["help_tags"],
    }
    pairs = []
    for mid in ev.shown_metrics(by):
        m = ev.metrics[mid]
        src = ev.sources[m["source"]]["name"] if m.get("source") else "—"
        pairs.append((metric_label(ev, mid),
                      t["help_metric"].format(label=m.get("description", m["label"]), source=src)))
    pairs += [
        (t["score"], t["help_score"]),
        (f"↑ {lb['up']}", t["help_up"].format(up=lb["up"])),
        (f"↓ {lb['down']}", t["help_down"].format(down=lb["down"])),
        (t["signals"], t["help_signals"].format(**lb)),
        (t["metric_sources"], t["help_metric_sources"]),
        (t["links"], t["help_links"]),
    ]
    for k, v in pairs:
        if k in cols:
            raise ValueError(f"two columns would both be called {k!r}; give the metric a different label")
        cols[k] = v
    return cols


def _fmt(v: float | None) -> str:
    if v is None:
        return ""
    return f"{v:,.0f}" if abs(v) >= 1000 or float(v).is_integer() else f"{v:,.1f}"


def _raw(v: float | None):
    """CSV 里写原始数字（不加千位分隔符），Excel 才能当数字用。"""
    if v is None:
        return ""
    return int(v) if float(v).is_integer() else round(v, 4)


def _cell(v):
    """以 = + - @ 开头的文字在 Excel 里会被当成公式，前面加个单引号。"""
    return "'" + v if isinstance(v, str) and v[:1] in ("=", "+", "-", "@") else v


def _metric_note(ev: Evidence, mid: str, v: dict) -> str:
    t = _t(ev)
    parts = [t["origin"][v["origin"]]]
    if v.get("note"):
        parts.append(v["note"])
    return "; ".join(parts)


def rows(ev: Evidence, ranked: list[dict], by: str) -> list[dict]:
    t, lb = _t(ev), labels(ev)
    keys = list(columns(ev, by))
    out = []
    for i, it in enumerate(ranked, 1):
        s, up, down = score(it)
        sigs = it.get("signals") or []
        msrc = []
        for mid in ev.shown_metrics(by):
            v = it["values"].get(mid)
            if v:
                where = v.get("url") or (ev.sources[ev.metrics[mid]["source"]]["url"] if ev.metrics[mid].get("source") else "")
                msrc.append(f"{ev.metrics[mid]['label']}: {_metric_note(ev, mid, v)} {where}".strip())
        row = [i, it["name"], it.get("subtitle", ""), ", ".join(it.get("tags") or [])]
        row += [_raw(it["values"].get(mid, {}).get("value")) for mid in ev.shown_metrics(by)]
        row += [s, up, down,
                "; ".join(f"{ARROW[g['trend']]} {ev.sources[g['source']]['name']} "
                          f"[{t['tiers'][ev.sources[g['source']]['tier']]}]: {g['claim']}" for g in sigs),
                " | ".join(msrc),
                " ".join(dict.fromkeys(ev.sources[g["source"]]["url"] for g in sigs))]
        out.append(dict(zip(keys, (_cell(x) for x in row))))
    return out


def guide_path(path: Path) -> Path:
    return path.with_name(f"{path.stem}.columns{path.suffix}")


def write_csv(ev: Evidence, ranked: list[dict], by: str, path: Path) -> Path:
    """写数据表和列说明，返回列说明的路径。utf-8-sig 让 Excel 正确识别中文。"""
    cols = columns(ev, by)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(cols))
        w.writeheader()
        w.writerows(rows(ev, ranked, by))
    guide = guide_path(path)
    with guide.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerows([["column", "meaning"], *cols.items()])
    return guide


# ---------------------------------------------------------------- HTML

def _e(s) -> str:
    return html.escape(str(s if s is not None else ""))


def _link(url: str, text: str, cls: str = "") -> str:
    """只给 http(s) 链接加 href，其他（比如 javascript:）只显示文字。"""
    if not str(url).lower().startswith(("http://", "https://")):
        return _e(text)
    c = f' class="{cls}"' if cls else ""
    return f'<a{c} href="{_e(url)}" target="_blank" rel="noopener noreferrer">{_e(text)}</a>'


def _row(ev: Evidence, i: int, it: dict, by: str) -> str:
    t, lb = _t(ev), labels(ev)
    s, up, down = score(it)
    cells = []
    for mid in ev.shown_metrics(by):
        v = it["values"].get(mid)
        text = _fmt(v["value"]) if v else "–"
        title = _metric_note(ev, mid, v) if v else ""
        inner = _link(v["url"], text) if v and v.get("url") else _e(text)
        cells.append((metric_label(ev, mid), "num", f'<span title="{_e(title)}">{inner}</span>'))
    cls = "pos" if s > 0 else "neg" if s < 0 else ""
    cells += [(t["score"], f"num {cls}", f"{s:+d}"), (f"↑ {lb['up']}", "num", up), (f"↓ {lb['down']}", "num", down)]
    tds = "".join(f'<td class="{c}" data-label="{_e(k)}">{v}</td>' for k, c, v in cells)
    sigs = "".join(
        f'<li><span class="arrow {g["trend"]}">{ARROW[g["trend"]]}</span>'
        f'{_link(ev.sources[g["source"]]["url"], ev.sources[g["source"]]["name"])}'
        f' <span class="tier {ev.sources[g["source"]]["tier"]}">{_e(t["tiers"][ev.sources[g["source"]]["tier"]])}</span>'
        f' {_e(g["claim"])}'
        + (f'<q>{_e(g["quote"])}</q>' if g.get("quote") else "") + "</li>"
        for g in it.get("signals") or [])
    tags = "".join(f'<span class="tag">{_e(x)}</span>' for x in it.get("tags") or [])
    return (f'<tr><td class="num rk">{i}</td>'
            f'<td class="name" data-rank="{i}"><b>{_e(it["name"])}</b>{tags}'
            f'<span class="sub">{_e(it.get("subtitle", ""))}</span></td>'
            f'{tds}<td class="evid" data-label="{_e(t["signals"])}"><ul>{sigs}</ul></td></tr>')


def render_html(ev: Evidence, ranked: list[dict], by: str, generated: str, fetched_at: str | None) -> str:
    t = _t(ev)
    cols = {k: v for k, v in columns(ev, by).items()
            if k not in (t["subtitle"], t["tags"], t["links"], t["metric_sources"])}
    head = [c for c in cols]
    thead = "".join(f"<th>{_e(c)}</th>" for c in head)
    body = "\n".join(_row(ev, i, it, by) for i, it in enumerate(ranked, 1))
    helps = "".join(f"<dt>{_e(k)}</dt><dd>{_e(v)}</dd>" for k, v in cols.items())
    stats = [(len(ranked), t["items"]), (len(ev.sources), t["sources"]), (sort_label(ev, by), t["sorted_by"])]
    stat_html = "".join(f'<div class="stat"><b>{_e(v)}</b><span>{_e(k)}</span></div>' for v, k in stats)
    live = f"{t['fetched']} · {fetched_at}" if fetched_at else t["not_fetched"] if ev.has_fetch() else ""
    refs = "".join(
        f'<li>{_link(s["url"], s["name"])} <span class="note">· {_e(t["tiers"][s["tier"]])}'
        f'{" · " + _e(s["date"]) if s.get("date") else ""}{" · " + _e(s["note"]) if s.get("note") else ""}</span></li>'
        for s in ev.sources.values())

    page = f"""<div class="wrap">
  <header>
    <p class="eyebrow">data-refinery · {_e(generated)}</p>
    <h1>{_e(ev.title)}</h1>
    {f'<p class="lede">{_e(ev.question)}</p>' if ev.question else ''}
    <div class="stats">{stat_html}</div>
    {f'<p class="live">{_e(live)}</p>' if live else ''}
  </header>
  <details class="colhelp"><summary>{_e(t["columns"])}</summary><dl>{helps}</dl></details>
  <div class="tablewrap"><table class="rank">
    <thead><tr>{thead}</tr></thead>
    <tbody>
{body}
    </tbody>
  </table></div>
  <footer>{_e(t["footer"].format(file=ev.path.name))}
    <details class="refs"><summary>{_e(t["refs"].format(n=len(ev.sources)))}</summary><ol>{refs}</ol></details>
  </footer>
</div>"""
    lang = "zh-CN" if ev.lang == "zh" else "en"
    return (f'<!doctype html>\n<html lang="{lang}">\n<head>\n<meta charset="utf-8">\n'
            f'<meta name="viewport" content="width=device-width, initial-scale=1">\n'
            f'<title>{_e(ev.title)}</title>\n<style>{CSS}</style>\n</head>\n<body>\n{page}\n</body>\n</html>\n')


def write_html(ev: Evidence, ranked: list[dict], by: str, generated: str, fetched_at: str | None,
               path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_html(ev, ranked, by, generated, fetched_at), encoding="utf-8")


